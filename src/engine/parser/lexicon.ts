/**
 * The words the studio understands. Everything is matched on normalised text (no diacritics,
 * unified alef/yaa/taa marbuta), and on stems with common prefixes (و ف ب ل ك ال) removed.
 */

export const norm = (s: string): string =>
  s
    .replace(/[ً-ٰٟـ]/g, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي');

/** Strips one or two leading particles and the article, longest first. */
export function stems(token: string): string[] {
  const out = new Set<string>([token]);
  let t = token;
  for (let i = 0; i < 2; i++) {
    const m = t.match(/^(و|ف|ب|ل|ك)(.{3,})$/);
    if (m) {
      t = m[2];
      out.add(t);
    }
  }
  for (const s of [...out]) {
    const a = s.match(/^(ال|لل)(.{2,})$/);
    if (a) out.add(a[2]);
  }
  return [...out];
}

